// Regenerates lib/countries.js — the full ISO 3166-1 alpha-2 country list —
// by probing Intl.DisplayNames, so no country ever needs to be hand-typed.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const dn = new Intl.DisplayNames(["en"], { type: "region" });
const A = "A".charCodeAt(0);
const countries = [];

for (let i = 0; i < 26; i++) {
  for (let j = 0; j < 26; j++) {
    const code = String.fromCharCode(A + i) + String.fromCharCode(A + j);
    let name;
    try {
      name = dn.of(code);
    } catch {
      continue;
    }
    // Intl echoes the code back for unassigned regions.
    if (!name || name === code) continue;
    // Skip meta/exceptional regions that aren't searchable places.
    if (["EU", "EZ", "UN", "QO", "ZZ", "XA", "XB"].includes(code)) continue;
    countries.push({ code, name });
  }
}

countries.sort((a, b) => a.name.localeCompare(b.name));

const out = `// AUTO-GENERATED by scripts/generate-countries.mjs — do not edit by hand.
// Full ISO 3166-1 alpha-2 region list (${countries.length} entries).
export const COUNTRIES = ${JSON.stringify(countries, null, 2)};

export const COUNTRY_NAME = Object.fromEntries(COUNTRIES.map((c) => [c.code, c.name]));
`;

const root = dirname(dirname(fileURLToPath(import.meta.url)));
writeFileSync(join(root, "lib", "countries.js"), out);
console.log(`Wrote lib/countries.js with ${countries.length} countries.`);
